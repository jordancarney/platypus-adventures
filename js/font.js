let atlas = null;
const index = new Map();
const tintCache = new Map();

export function buildFont() {
  if (atlas) return;
  const chars = Object.keys(G);
  atlas = document.createElement('canvas');
  atlas.width = chars.length * GW;
  atlas.height = GH;
  const g = atlas.getContext('2d');
  g.fillStyle = '#ffffff';
  chars.forEach((ch, i) => {
    index.set(ch, i);
    const rows = G[ch];
    for (let y = 0; y < GH; y++) {
      const row = rows[y] || '';
      for (let x = 0; x < GW; x++) if (row[x] === '#') g.fillRect(i * GW + x, y, 1, 1);
    }
  });
}

function tinted(color) {
  let c = tintCache.get(color);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = atlas.width; c.height = atlas.height;
  const g = c.getContext('2d');
  g.drawImage(atlas, 0, 0);
  g.globalCompositeOperation = 'source-in';
  g.fillStyle = color;
  g.fillRect(0, 0, c.width, c.height);
  tintCache.set(color, c);
  return c;
}

// Rendered width in internal pixels (trailing letter-space excluded).
export const textWidth = (str, scale = 1) =>
  String(str).length ? String(str).length * ADVANCE * scale - scale : 0;

// Characters without art fall back to '?', so add a glyph above rather than relying on it.

export function drawText(ctx, str, x, y, opts = {}) {
  buildFont();
  const { scale = 1, color = '#f0ead8', align = 'left', alpha = 1, shadow = true } = opts;
  str = String(str);
  const w = textWidth(str, scale);
  let px = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const py = Math.round(y);

  ctx.save();
  ctx.globalAlpha *= alpha;
  ctx.imageSmoothingEnabled = false;
  const blit = (img, ox, oy) => {
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === ' ') continue;
      const gi = index.has(ch) ? index.get(ch) : index.get('?');
      ctx.drawImage(img, gi * GW, 0, GW, GH,
        ox + i * ADVANCE * scale, oy, GW * scale, GH * scale);
    }
  };
  if (shadow) {
    ctx.save();
    ctx.globalAlpha *= 0.75;
    blit(tinted('#000000'), px + scale, py + scale);
    ctx.restore();
  }
  blit(tinted(color), px, py);
  ctx.restore();
}
